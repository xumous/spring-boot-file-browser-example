-- 检查G1002的座位数据
SELECT COUNT(*)                                         as seat_count,
       SUM(CASE WHEN seat_status = 0 THEN 1 ELSE 0 END) as available_seats,
       SUM(CASE WHEN seat_status = 1 THEN 1 ELSE 0 END) as sold_seats,
       SUM(CASE WHEN seat_status = 2 THEN 1 ELSE 0 END) as locked_seats
FROM seat_info si
         INNER JOIN carriage_info ci ON si.carriage_id = ci.carriage_id
WHERE ci.train_id = 'G1002';

